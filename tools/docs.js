// Writes docs/ODDS.md: the exact chance of everything in the game, straight from the engine
// (badges.js and data.js) and from the item, drop and slot tables in app.js.
//   node tools/docs.js
'use strict';
globalThis.crypto ??= require('crypto').webcrypto;
globalThis.RNG_NO_AUTOSTART = true;
const fs = require('fs');
const path = require('path');
require('../badges.js');
require('../data.js');
const { createGame, pExp, E_MAX } = globalThis.RNGEngine;
const data = globalThis.RNG_DATA;
const g = createGame(10, { counts: data.counts, quantiles: data.quantiles });

const fmt = n => Math.round(n).toLocaleString('en-US');
const rollsText = k => `${fmt(k)} ${k === 1 ? 'roll' : 'rolls'}`;
const oneIn = p => (p >= 0.5 ? `1 in ${(1 / p).toFixed(2)}` : p >= 0.1 ? `1 in ${(1 / p).toFixed(1)}` : `1 in ${fmt(1 / p)}`);
const pct = p => (p >= 0.001 ? `${+(100 * p).toPrecision(3)}%` : `${+(100 * p).toPrecision(2)}%`);
const rar = i => g.RARITIES[i].name;

// The game tables live in app.js; take each one out by its declaration and evaluate it alone.
const app = fs.readFileSync(path.join(__dirname, '..', 'app.js'), 'utf8');
function grab(decl) {
  const start = app.indexOf(decl);
  if (start < 0) throw new Error(`app.js has no ${decl}`);
  let depth = 0, i = app.indexOf('=', start) + 1;
  for (; i < app.length; i++) {
    const c = app[i];
    if ('[{('.includes(c)) depth++;
    if (']})'.includes(c)) depth--;
    if (c === ';' && depth === 0) break;
  }
  return app.slice(app.indexOf('=', start) + 1, i);
}
const scope = { fmt, rollsText, MODES: g.MODES };
const run = src => Function(...Object.keys(scope), `return (${src});`)(...Object.values(scope));
scope.luckItem = run(grab('const luckItem ='));
scope.dropItem = run(grab('const dropItem ='));
const ITEMS = run(grab('const ITEMS ='));
const NAME = Object.fromEntries(ITEMS.map(i => [i.id, i.name]));
const DROPS = run(grab('const DROPS ='));
const COIN_FROM = run(grab('const COIN_FROM ='));
const COIN_CHANCE = run(grab('const COIN_CHANCE ='));
const SLOT_UNITS = run(grab('const SLOT_UNITS ='));
const SLOT_PRIZES = run(grab('const SLOT_PRIZES ='));
const SLOT_PITY = run(grab('const SLOT_PITY ='));
const QUESTS = run(grab('const QUESTS ='));
const QUEST_BONUS = run(grab('const QUEST_BONUS ='));
const BOOK = run(grab('const BOOK ='));
const PRESTIGE_STEP = run(grab('const PRESTIGE_STEP ='));
const BUNDLE_PRICE = run(grab('const BUNDLE_PRICE ='));
const TOKENS_PER = run(grab('const TOKENS_PER ='));
const levelCost = run(grab('const levelCost ='));

const out = [];
const p = (...lines) => out.push(...lines);
const table = (head, rows) => {
  const RIGHT = ['Tokens', 'Trash', '1/10 or rarer', '1/100 or rarer', '1/1,000 or rarer', '1/10,000 or rarer', 'Luck', 'Cost of this level', 'Total tokens', 'About this many Standard rolls', 'Starts at', 'Share of all rolls', 'About', 'Numbers', 'Chance', 'EP', 'Chance per roll', 'Odds', 'Hard pity', 'Coins', 'Badges needed', 'Rarest needed'];
  p(`| ${head.join(' | ')} |`, `|${head.map(h => (RIGHT.includes(h) ? ' ---: ' : ' --- ')).join('|')}|`);
  for (const r of rows) p(`| ${r.join(' | ')} |`);
  p('');
};

p('# Long Shot 10: every chance in the game', '',
  'Generated by `tools/docs.js` from the game itself, so these are the numbers the game really uses. Badge chances are exact counts over all 10,000,000,000 rolls; nothing here is estimated except where it says so.', '',
  '- [Roll tiers](#roll-tiers)', '- [Badges](#badges)', '- [Mode badges](#mode-badges)', '- [Multipliers](#multipliers)', '- [Exponents](#exponents)',
  '- [Difficulties](#difficulties)', '- [Lucky tokens and luck levels](#lucky-tokens-and-luck-levels)', '- [Coins and item drops](#coins-and-item-drops)', '- [Coin slot](#coin-slot)', '- [Items](#items)', '- [Daily quests](#daily-quests)', '- [Badge book](#badge-book)', '- [Prestige](#prestige)', '');

p('## Roll tiers', '',
  'Every roll gets a 1/N: the chance that a random roll of the same mode scores at least as high. Its tier comes from N. Because N is defined that way, a roll of 1/N or rarer turns up exactly 1 time in N, in every mode, so these shares are exact.', '');
const shares = g.tierShares();
table(['Tier', 'Starts at', 'Share of all rolls', 'About'], g.ROLL_TIERS.map(t => {
  const r = g.RARITIES.find(x => x.id === t.id);
  return [t.name, t.id === 'trash' ? 'bottom 1%' : `1/${fmt(r.from)}`, pct(shares[t.id]), shares[t.id] > 0 ? oneIn(shares[t.id]) : ''];
}));
p('Badges and multipliers use the same ladder: a badge that comes up 1 time in 3,000 is Anomaly, because 3,000 is past Anomaly\'s 2,500.', '');

p('## Badges', '',
  `${g.BADGES.length} badges, plus ${g.MODES.reduce((t, m) => t + m.badges.length, 0)} that only exist in one mode and 5 that change with the date. A badge is worth EP equal to its odds (a 1 in 143 badge gives 143 EP). Within a group (marked) only the rarest badge you hit counts.`, '');
for (const cat of g.CATEGORIES.filter(c => !['Powers', 'Modulo', 'Target', 'Radar', 'Daily'].includes(c))) {
  const list = g.BADGES.filter(b => b.cat === cat).sort((a, b) => b.p - a.p);
  p(`### ${cat} (${list.length})`, '');
  table(['Badge', 'What it takes', 'Numbers', 'Chance', 'Rarity', 'EP'],
    list.map(b => [`${b.name}${b.group ? ' ᵍ' : ''}`, b.desc.replace(/\|/g, '/'), fmt(b.count), oneIn(b.p), rar(b.rarity), fmt(b.ep)]));
}
p('ᵍ in a group: only the rarest badge of its group counts on a roll.', '');
const daily = g.datedBadges('2026-10-17');
p('### Daily (5)', '', 'These depend on the date of the roll; the chances below are for 17 October 2026.', '');
table(['Badge', 'What it takes', 'Chance', 'Rarity'], daily.map(b => [b.name, b.desc, oneIn(b.p), rar(b.rarity)]));

p('## Mode badges', '');
for (const m of g.MODES.filter(x => x.badges.length)) {
  p(`### ${m.name}`, '', m.desc, '');
  table(['Badge', 'What it takes', 'Chance per roll', 'Rarity'], m.badges.slice().sort((a, b) => b.p - a.p).map(b => [b.name, b.desc, oneIn(b.p), rar(b.rarity)]));
}

p('## Multipliers', '',
  `The second reel lands on one of ${g.MULTIPLIERS.length - 1} multipliers or on ×1. Each chance is a whole number of parts in 10¹⁵.`, '');
table(['Multiplier', 'Name', 'Chance', 'Rarity'], g.MULTIPLIERS.slice().sort((a, b) => b.p - a.p).map(m => [`×${m.symbol}`, m.name, `${oneIn(m.p)} (${pct(m.p)})`, rar(m.rarity)]));

p('## Exponents', '', `In Exponent mode the exponent is 1 half the time, 2 a quarter of the time, and so on, halving each step up to ${E_MAX}.`, '');
table(['Exponent', 'Chance'], [1, 2, 3, 4, 5, 6, 8, 10, 12, 20, E_MAX].map(e => [String(e), oneIn(pExp(e))]));

p('## Difficulties', '',
  'A difficulty changes your score but not the yardstick: 1/N always compares a roll with the Standard game of its mode. So harder difficulties reach each tier far less often. Charms and lenses are paused on every difficulty but Standard. These frequencies come from 400,000 sampled Classic rolls each (0 means none turned up).', '');
{
  const R = 4e5, rows = [];
  for (const d of g.DIFFICULTIES) {
    let trash = 0; const k = [0, 0, 0, 0];
    for (let i = 0; i < R; i++) {
      const r = g.score(g.randomRoll(), null, { ...g.randomParams('classic'), d: d.id }), t = g.rollTier(r.rank, 'classic');
      if (t.tier.id === 'trash') trash++;
      for (let j = 0; j < 4; j++) if (t.oneInLog >= j + 1) k[j]++;
    }
    const f = v => (v ? oneIn(v / R) : '0 in 400,000');
    rows.push([d.name, d.desc, `×${TOKENS_PER[d.id]}`, pct(trash / R), f(k[0]), f(k[1]), f(k[2]), f(k[3])]);
  }
  table(['Difficulty', 'Rule', 'Tokens', 'Trash', '1/10 or rarer', '1/100 or rarer', '1/1,000 or rarer', '1/10,000 or rarer'], rows);
}

p('## Lucky tokens and luck levels', '',
  'Every roll, on any tier, has a 1 in 2 chance to drop lucky tokens: 1 on Standard, more on harder difficulties (see above). Tokens buy permanent luck levels. At level k every roll is the best of k + 1 rolls, which makes a roll of 1/N or rarer about k + 1 times as likely. Each level costs 12% more than the one before, rounded up. Levels and tokens survive prestige.', '');
{
  const rows = []; let total = 0;
  for (let k = 0; k < 200; k++) {
    total += levelCost(k);
    if ([0, 1, 2, 4, 9, 19, 49, 99, 149, 199].includes(k)) rows.push([`${k + 1}`, `×${k + 2}`, fmt(levelCost(k)), fmt(total), rollsText(2 * total)]);
  }
  table(['Level', 'Luck', 'Cost of this level', 'Total tokens', 'About this many Standard rolls'], rows);
}
p('Luck above ×32 (a charm, your level, or both multiplied together) is drawn straight from the exact odds of the best of that many rolls instead of rolling every one, so it is instant at any size. It matches the true best-of distribution: checked against it in every mode at ×100,000 and ×10,000,000, and in Classic, Exponent and Prime radar at ×33 and ×1,000.', '');

p('## Coins and item drops', '',
  `Rolls made with a luck charm or a lens never drop items or coins; permanent luck does not stop them. A roll of 1/${fmt(COIN_FROM)} or rarer has a 1 in ${Math.round(1 / COIN_CHANCE)} chance of a coin. Items drop by the roll's 1/N; each row covers rolls from its N up to the next row.`, '');
table(['Roll', 'Items and chances'], DROPS.map(([n, items], i) => [`1/${fmt(n)}${i === DROPS.length - 1 ? ' or rarer' : ''}`, items.map(([id, c]) => `${NAME[id]} ${pct(c)}`).join(', ')]));
p('Drop boosters (Horn of Plenty ×25, Golden Goose ×100, Diamond Goose ×1,000) and prestige multiply every chance above, coins included. Past 100%, the whole part drops for sure and the rest is a chance at one more.', '',
  'Put together, a plain roll drops a coin about ' +
  `${oneIn(COIN_CHANCE / COIN_FROM)}, and a Charm of Ten about ${oneIn(DROPS.reduce((t, [n, items], i) => { const next = DROPS[i + 1] ? DROPS[i + 1][0] : Infinity; const share = 1 / n - 1 / next; const c = (items.find(x => x[0] === 'luck10') || [0, 0])[1]; return t + share * c; }, 0))}.`, '');

p('## Coin slot', '', `One coin per spin. Every spin wins exactly one prize from this table, in parts of ${fmt(SLOT_UNITS)}.`, '');
table(['Prize', 'Chance', 'Odds', 'Hard pity'], SLOT_PRIZES.map(([id, q, u]) => [`${NAME[id]}${q > 1 ? ` ×${q}` : ''}`, pct(u / SLOT_UNITS), oneIn(u / SLOT_UNITS), id in SLOT_PITY ? `${fmt(SLOT_PITY[id])} spins` : '']));
p('Hard pity: go that many spins without the prize and the next spin pays it for sure. Winning one naturally resets its count. If two are due at once, the rarer one is paid first and the other on the next spin.', '');

p('## Items', '');
table(['Item', 'What it does', 'Fuses into'], ITEMS.filter(i => !i.retired).map(i => [i.name, i.desc, i.next ? `${i.next[1]} → 1 ${NAME[i.next[0]]}` : '']));
p('Retired items (Charm of Two, Charm of Five, Magnet, Treasure Map) no longer drop but still work and fuse upwards. Fuse all fuses every full set of one item; Fuse everything works up every line from the bottom, so new items feed the next fuse.', '');

p('## Daily quests', '', `Three quests a day per save file, picked from this list by the date. Finishing all three adds a ${NAME[QUEST_BONUS]}.`, '');
table(['Quest', 'Coins', 'Item'], QUESTS.map(q => [q.text, String(q.coins), NAME[q.item]]));

p('## Badge book', '', 'A page is complete when you own every badge of its category with a chance of at least 1 in 1,000,000.', '');
const collectable = g.BADGES.concat(g.MODES.flatMap(m => m.badges));
table(['Page', 'Badges needed', 'Rarest needed', 'Reward'], BOOK.map(b => {
  const list = collectable.filter(x => x.cat === b.cat && x.p >= 1e-6);
  return [b.cat, String(list.length), oneIn(Math.min(...list.map(x => x.p))), b.skin ? `${b.skin} skin` : `${NAME[b.item]}${b.k > 1 ? ` ×${b.k}` : ''}`];
}));

p('## Prestige', '',
  `Prestige k needs ${fmt(PRESTIGE_STEP)} × k rolls since the previous one (${fmt(PRESTIGE_STEP)}, then ${fmt(2 * PRESTIGE_STEP)}, …). It clears coins, items and active effects, and multiplies every drop and coin chance by 1 + 0.5 × k for good: ×1.5 at prestige 1, ×2 at 2, ×3.5 at 5.`, '',
  `The skin bundle (Gold, Ruby and Aurora) costs ${BUNDLE_PRICE} coins.`, '');

fs.mkdirSync(path.join(__dirname, '..', 'docs'), { recursive: true });
fs.writeFileSync(path.join(__dirname, '..', 'docs', 'ODDS.md'), out.join('\n'));
console.log(`wrote docs/ODDS.md (${out.length} lines)`);
